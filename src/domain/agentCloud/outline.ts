export const agentCloudDocument = 'Agent-native cloud architecture - reviewed public-source extension';

export function extendNeuralOutline(base: RoadmapPackOutline): RoadmapPackOutline {
  if (base.missionId !== 'neural') throw new Error('Agent-cloud learning extends only Neural Edge.');
  return {
    ...base,
    title: 'Operation Neural Edge - AI Architecture and Agent-Native Cloud',
    overview: `${base.overview} The research extension develops cloud for agents and cloud engineering/operations with agents through bounded execution, identity, durable workflows, independent verification and measured economics.`,
    sourceKind: 'mixed',
    reviewedAt: agentCloudReviewedAt,
    webSources: agentCloudSources,
    sourceNotes: [...base.sourceNotes,
      'The original 144-page workbook and its 28 checkpoints remain unchanged. The v4 append adds 12 authored checkpoints and four optional cases from reviewed public sources; it is not content extracted from additional PDF pages.',
      'Extension source review: 2026-11-09. Product contracts, first-party accounts, historical studies and original simulations have different evidence limits. No paid account, real customer data or production access is mandatory.',
      'Opening the library/map does not adopt v4. Confirmed v3-to-v4 adoption retains the verified identical prefix and archives its exact position; earlier non-equivalent editions remain archived without guessed completion.',
    ],
    phases: [...base.phases, ...agentCloudPhases],
    units: [...base.units, ...agentCloudUnits],
    exerciseCount: base.exerciseCount + agentCloudUnits.reduce((total, unit) => total + unit.exerciseCount, 0),
  };
}
